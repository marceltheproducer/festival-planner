// Equirectangular projection cropped to the populated range so the map fills
// the figure instead of drowning festivals in empty ocean and polar ice.
const LNG_MIN = -135, LNG_MAX = 160, LAT_MIN = -42, LAT_MAX = 66;

export function projectXY(lat: number, lng: number): { x: number; y: number } {
  return {
    x: ((lng - LNG_MIN) / (LNG_MAX - LNG_MIN)) * 100,
    y: ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * 100,
  };
}
